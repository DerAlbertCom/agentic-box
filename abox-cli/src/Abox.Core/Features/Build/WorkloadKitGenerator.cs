using System.Text;
using System.Text.RegularExpressions;
using Abox.Features.Shared.Builds;
using Abox.Features.Shared.Common;
using Abox.Features.Shared.Squads;

namespace Abox.Features.Build;

/// <summary>
/// Turns a workload into a sandbox kit: a descriptor and the Dockerfile the image is built from.
/// </summary>
internal sealed class WorkloadKitGenerator
{
    private const string CertificatesDirectoryName = "certificates";
    private const string CertificateResourcePrefix = "Abox.Features.Build.Assets.certificates.";
    private const string ContainerCertificatesDirectory = "/usr/local/share/ca-certificates/abox";
    private const string SystemCertificateBundle = "/etc/ssl/certs/ca-certificates.crt";

    // Tools that ignore the system store, pointed at it once for the build and the sandbox.
    // docs/corporate-certificates.md lists why each one is here.
    private static readonly (string Name, string Value)[] TrustEnvironment =
    [
        ("MISE_EXTRA_CA_CERTS", SystemCertificateBundle),
        ("NODE_EXTRA_CA_CERTS", SystemCertificateBundle),
        ("REQUESTS_CA_BUNDLE", SystemCertificateBundle),
        ("AWS_CA_BUNDLE", SystemCertificateBundle),
        ("UV_SYSTEM_CERTS", "true"),
    ];

    /// <summary>The name of the generated workload kit descriptor, without the extension.</summary>
    public const string KitName = "workload";

    /// <summary>The directory the scripts of the workload are copied into.</summary>
    public const string ScriptsDirectoryName = "scripts";

    /// <summary>
    /// Writes the kit into a directory, replacing what was there before.
    /// </summary>
    /// <param name="workload">The workload to turn into a kit.</param>
    /// <param name="targetDirectory">The directory the kit is written to.</param>
    /// <param name="baseImage">The image the workload builds on, pinned by digest; null means its template as written.</param>
    public void Generate(WorkloadFile workload, string targetDirectory, string? baseImage = null)
    {
        var scripts = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        foreach (var script in workload.Scripts)
        {
            var fileName = Path.GetFileName(script);
            if (!scripts.TryAdd(fileName, script))
            {
                throw new AboxException(
                    $"The scripts '{scripts[fileName]}' and '{script}' have the same output file name '{fileName}'."
                );
            }
        }

        Directory.CreateDirectory(targetDirectory);

        WriteDescriptor(workload, targetDirectory);
        WriteDockerfile(workload, baseImage ?? workload.Template, targetDirectory);
        WriteCertificates(targetDirectory);
        CopyScripts(workload, targetDirectory);
    }

    private static void WriteDescriptor(WorkloadFile workload, string targetDirectory)
    {
        var descriptor = new StringBuilder()
            .AppendLine("# syntax=docker/sandbox-kit:3")
            .AppendLine("schemaVersion: \"3\"")
            .AppendLine("kind: workload")
            .AppendLine($"displayName: {YamlScalar.Quote(workload.Name)}")
            .AppendLine(
                $"description: {YamlScalar.Quote($"The base image built from {Path.GetFileName(workload.Path)}.")}"
            )
            .AppendLine("capabilities:")
            .AppendLine("  - type: com.docker.sandbox/sbx@1")
            .ToString();

        File.WriteAllText(
            Path.Combine(targetDirectory, KitName + ".yaml"),
            descriptor.ReplaceLineEndings("\n")
        );
    }

    private static void WriteDockerfile(
        WorkloadFile workload,
        string baseImage,
        string targetDirectory
    )
    {
        var dockerfile = new StringBuilder()
            .AppendLine("# syntax=docker/dockerfile:1")
            .AppendLine(
                $"# Generated by abox from {Path.GetFileName(workload.Path)}. Change the workload, not this file."
            )
            .AppendLine($"FROM {baseImage}")
            .AppendLine()
            .AppendLine("# Trust the bundled RWE CAs before any network downloads.")
            .AppendLine("USER root")
            .AppendLine($"COPY {CertificatesDirectoryName}/ {ContainerCertificatesDirectory}/")
            .AppendLine("RUN update-ca-certificates");
        foreach (var (name, value) in TrustEnvironment)
        {
            dockerfile.AppendLine($"ENV {name}=\"{value}\"");
        }
        dockerfile.AppendLine("USER agent").AppendLine();

        AppendAptPackages(dockerfile, workload);
        AppendMiseBootstrap(dockerfile, workload);
        AppendMiseTools(dockerfile, workload);
        AppendScripts(dockerfile, workload);
        dockerfile.AppendLine("WORKDIR /home/agent/workspace");

        File.WriteAllText(
            Path.Combine(targetDirectory, KitName + ".dockerfile"),
            dockerfile.ToString().ReplaceLineEndings("\n")
        );
    }

    private static void AppendAptPackages(StringBuilder dockerfile, WorkloadFile workload)
    {
        if (workload.Apt.Count > 0)
        {
            var install = new StringBuilder()
                .AppendLine("    apt-get update \\")
                .AppendLine(
                    "    && DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends \\"
                );

            foreach (var package in workload.Apt)
            {
                install.AppendLine($"    {package} \\");
            }

            install.Append("    && apt-get clean && rm -rf /var/lib/apt/lists/*");

            dockerfile
                .AppendLine(
                    "# The apt packages are installed in one step, system before tools, as root."
                )
                .AppendLine("USER root")
                .AppendLine("RUN \\")
                .Append(install.ToString())
                .AppendLine()
                .AppendLine("USER agent")
                .AppendLine();
        }
    }

    private static void AppendMiseBootstrap(StringBuilder dockerfile, WorkloadFile workload)
    {
        if (workload.Mise.Count > 0 || workload.Scripts.Count > 0)
        {
            dockerfile
                .AppendLine("# mise manages the tools of this image, as the agent user.")
                .AppendLine(
                    "ENV PATH=\"/home/agent/.local/bin:/home/agent/.local/share/mise/shims:${PATH}\""
                )
                .AppendLine("USER agent")
                .AppendLine("RUN set -eu; \\")
                .AppendLine("    if ! command -v mise >/dev/null 2>&1; then \\")
                .AppendLine("      installer=\"$(mktemp)\"; \\")
                .AppendLine("      curl -fsSL https://mise.run -o \"$installer\"; \\")
                .AppendLine("      sh \"$installer\"; \\")
                .AppendLine("      rm -f \"$installer\"; \\")
                .AppendLine("    fi; \\")
                .AppendLine("    mise --version")
                .AppendLine();
        }
    }

    private static void AppendMiseTools(StringBuilder dockerfile, WorkloadFile workload)
    {
        if (workload.Mise.Count > 0)
        {
            dockerfile
                .AppendLine(
                    "# One install step per tool, in the order of the workload, so a tool that runs into a rate limit does not hold up the others."
                )
                .AppendLine(
                    "# The versions of a tool are installed in one step, the last one first, because mise activates the first entry of its list."
                );

            foreach (var (tool, versions) in GroupTools(workload.Mise))
            {
                dockerfile
                    .AppendLine(
                        $"RUN --mount=type=secret,id={WorkloadBuildSecrets.GitHubToken},required=false \\"
                    )
                    .AppendLine(
                        $"    GITHUB_TOKEN=\"$(cat /run/secrets/{WorkloadBuildSecrets.GitHubToken} 2>/dev/null || true)\" \\"
                    )
                    .AppendLine($"    mise use -g -y {string.Join(' ', versions)}");
            }

            dockerfile.AppendLine();
        }
    }

    private static void AppendScripts(StringBuilder dockerfile, WorkloadFile workload)
    {
        if (workload.Scripts.Count > 0)
        {
            dockerfile
                .AppendLine("# The scripts of the workload run while the image is built.")
                .AppendLine($"COPY {ScriptsDirectoryName}/ /tmp/abox-{ScriptsDirectoryName}/");

            foreach (var script in workload.Scripts)
            {
                dockerfile.AppendLine(
                    $"RUN bash /tmp/abox-{ScriptsDirectoryName}/{Path.GetFileName(script)}"
                );
            }

            dockerfile.AppendLine();
        }
    }

    /// <summary>
    /// The tools of a workload, grouped by tool in the order of their first entry. The
    /// versions of one tool are installed in one step, so mise keeps them all, and they
    /// are reversed, so the version that comes last in the workload is the one mise
    /// activates.
    /// </summary>
    internal static IReadOnlyList<(string Tool, IReadOnlyList<string> Versions)> GroupTools(
        IReadOnlyList<string> specs
    )
    {
        var groups = new List<(string Tool, List<string> Versions)>();
        var byTool = new Dictionary<string, List<string>>(StringComparer.Ordinal);

        foreach (var spec in specs)
        {
            var tool = ToolName(spec);

            if (!byTool.TryGetValue(tool, out var versions))
            {
                versions = [];
                byTool[tool] = versions;
                groups.Add((tool, versions));
            }

            versions.Add(spec);
        }

        return groups
            .Select(group =>
                (
                    group.Tool,
                    (IReadOnlyList<string>)group.Versions.AsEnumerable().Reverse().ToList()
                )
            )
            .ToList();
    }

    /// <summary>The tool of a spec, without its version.</summary>
    private static string ToolName(string spec)
    {
        var at = spec.LastIndexOf('@');
        return at > 0 ? spec[..at] : spec;
    }

    private static void CopyScripts(WorkloadFile workload, string targetDirectory)
    {
        var scriptsDirectory = Path.Combine(targetDirectory, ScriptsDirectoryName);

        if (Directory.Exists(scriptsDirectory))
        {
            Directory.Delete(scriptsDirectory, recursive: true);
        }

        if (workload.Scripts.Count == 0)
        {
            return;
        }

        Directory.CreateDirectory(scriptsDirectory);

        foreach (var script in workload.Scripts)
        {
            var source = Path.Combine(workload.Directory, script);
            if (!File.Exists(source))
            {
                throw new AboxException(
                    $"The script '{script}' of '{workload.Path}' does not exist."
                );
            }

            var bytes = File.ReadAllBytes(source);
            var length = 0;
            for (var index = 0; index < bytes.Length; index++)
            {
                if (bytes[index] == '\r' && index + 1 < bytes.Length && bytes[index + 1] == '\n')
                    continue;
                bytes[length++] = bytes[index];
            }
            File.WriteAllBytes(
                Path.Combine(scriptsDirectory, Path.GetFileName(script)),
                bytes.AsSpan(0, length)
            );
        }
    }

    private static void WriteCertificates(string targetDirectory)
    {
        var directory = Path.Combine(targetDirectory, CertificatesDirectoryName);
        if (Directory.Exists(directory))
        {
            Directory.Delete(directory, recursive: true);
        }
        Directory.CreateDirectory(directory);

        // The CAs are embedded so an installed tool never needs the repository or host trust store.
        // Each file holds one CA, as update-ca-certificates expects; public roots come from the template.
        foreach (var (fileName, resourceName) in BundledCertificates())
        {
            using var resource = typeof(WorkloadKitGenerator).Assembly.GetManifestResourceStream(
                resourceName
            )!;
            using var output = File.Create(Path.Combine(directory, fileName));
            resource.CopyTo(output);
        }
    }

    /// <summary>The bundled CA certificates as output file name and resource name, in name order.</summary>
    internal static IReadOnlyList<(string FileName, string ResourceName)> BundledCertificates()
    {
        var certificates = typeof(WorkloadKitGenerator)
            .Assembly.GetManifestResourceNames()
            .Where(name => name.StartsWith(CertificateResourcePrefix, StringComparison.Ordinal))
            .Order(StringComparer.Ordinal)
            .Select(name => (name[CertificateResourcePrefix.Length..], name))
            .ToList();
        return certificates.Count > 0
            ? certificates
            : throw new InvalidOperationException("The bundled RWE CA certificates are missing.");
    }
}
